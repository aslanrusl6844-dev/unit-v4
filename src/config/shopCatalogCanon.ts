/** Все типы раздела по порядку приложения, без повторов (одинаковый тип на разных полках — один). */
export function canonTypesOf(category: string): string[] {
  const s = SHOP_CATALOG_CANON[category];
  if (!s) return [];
  const seen = new Set<string>();
  const out: string[] = [];
  for (const t of [...s.shelves.flatMap((x) => x.types), ...s.types]) {
    const k = t.toLowerCase();
    if (!seen.has(k)) { seen.add(k); out.push(t); }
  }
  return out;
}
